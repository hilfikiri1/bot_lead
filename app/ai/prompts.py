CATALOG_DISCLAIMER = (
    "Информация в каталоге сформирована автоматически на основании данных, "
    "размещённых поставщиком на платформе 1688.com. "
    "Перевод носит информационный характер. "
    "Цена, минимальный заказ, характеристики, комплектация и наличие "
    "подлежат дополнительному подтверждению у поставщика."
)


def build_user_message(
    title_zh: str,
    price_raw: str | None,
    price_tiers_raw: list[str],
    moq_raw: str | None,
    specifications: list[tuple[str, str]],
    variants: list[tuple[str, list[str]]],
    supplier: str | None,
) -> str:
    lines = [
        "Подготовь содержание каталога для следующего товара:\n",
        f"**Название (китайский):** {title_zh}",
    ]

    if supplier:
        lines.append(f"**Поставщик:** {supplier}")

    if price_raw:
        lines.append(f"**Цена (исходный текст):** {price_raw}")
    else:
        lines.append("**Цена:** не указана")

    if price_tiers_raw:
        lines.append("**Ступенчатые цены:**")
        for tier in price_tiers_raw:
            lines.append(f"  - {tier}")

    if moq_raw:
        lines.append(f"**Минимальный заказ:** {moq_raw}")

    if specifications:
        lines.append("**Характеристики:**")
        for name, value in specifications:
            lines.append(f"  - {name}: {value}")

    if variants:
        lines.append("**Варианты:**")
        for name, values in variants:
            lines.append(f"  - {name}: {', '.join(values)}")

    lines.append(
        "\nВ поле `disclaimer` используй стандартный дисклеймер о необходимости "
        "уточнения данных у поставщика."
    )

    return "\n".join(lines)
